"""Generate the BUILD-01 public DTOs from the master-kit source contracts."""
import json
import subprocess
from pathlib import Path
import yaml

root = Path(__file__).resolve().parents[1]
contracts = root.parent / 'master-kit (1)' / 'contracts' / 'core-api'
document = yaml.safe_load((contracts / 'openapi.yaml').read_text(encoding='utf-8'))


def ts(schema: dict) -> str:
    if '$ref' in schema:
        reference = schema['$ref']
        if '/properties/' in reference:
            target = document
            for token in reference[2:].split('/'):
                target = target[token]
            return ts(target)
        return reference.rsplit('/', 1)[-1]
    for composition, operator in [('oneOf', ' | '), ('anyOf', ' | '), ('allOf', ' & ')]:
        if composition in schema:
            return operator.join('(' + ts(branch) + ')' for branch in schema[composition])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    kind = schema.get('type')
    if isinstance(kind, list):
        return ' | '.join(ts({**schema, 'type': part}) for part in kind)
    if kind == 'object':
        if not schema.get('properties') and isinstance(schema.get('additionalProperties'), dict):
            return 'Record<string, ' + ts(schema['additionalProperties']) + '>'
        required = schema.get('required', [])
        return '{ ' + ' '.join(f'{key}{"" if key in required else "?"}: {ts(value)};'
                               for key, value in schema.get('properties', {}).items()) + ' }'
    if kind == 'array':
        return '(' + ts(schema['items']) + ')[]'
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


output = '// Generated by scripts/generate-types.py from master-kit (1). Do not edit.\n'
for name in ['CurrentUser', 'LoginRequest', 'LoginResponse', 'PasswordChangeRequest', 'WorkspaceSummary',
    'AdminAccountSearchResponse', 'AdminAccountDetail', 'AdminRoleChange', 'AdminSessionList', 'AdminIdentityStatus',
    'InvitationRequest', 'InvitationCreatedResponse', 'AcceptInvitationRequest', 'InvitationRequiresMfaResponse',
    'MfaSetupChallengeResponse', 'MfaEnrollmentResponse', 'MfaEnrollmentCompleteResponse', 'RequiredMfaEnrollmentResponse',
    'MfaStatusResponse', 'MfaRolePolicyListResponse', 'MfaRolePolicyResponse', 'CsvImportCreated', 'CsvImportPreview',
    'CsvImportRowOutcome', 'CsvImportCommit', 'Module', 'CourseDetail', 'CourseList',
    'FacultyView', 'AcademicTermView', 'TeachingSessionView', 'TeachingSession',
    'TeachingSessionSeries', 'TeachingSessionException', 'LessonPlanView',
    'GradeComponent', 'GradeBand', 'GradeSchemeDraft', 'GradeSchemeView', 'CourseGradeSchemeList',
    'CourseResource', 'CourseResourceView', 'CourseResourcesDraft', 'CourseResourcesView', 'EffectiveCourseRule',
    'CourseRuleTemplateView', 'Rule', 'PlanEntry', 'DisableRule', 'OverrideRule', 'EffectiveCourseRules', 'PersistenceStatus',
    'PersonalProfile', 'ProfileChange', 'IdentityPolicyView', 'IdentityPolicyChange', 'PersonalSession', 'PersonalSessionList',
    'RecoveryStatus', 'RecoveryRequested', 'PasswordResetRequest', 'PasswordResetComplete', 'AccountExportCreated', 'AccountExportRequest',
    'SupportPerson', 'SupportPersonList', 'SupportProfile', 'SupportProfileChange', 'CourseStaffProfile', 'CourseStaffProfiles']:
    output += f'export type {name} = {ts(document["components"]["schemas"][name])};\n'
prefs = json.loads((contracts / 'user-preferences.schema.json').read_text(encoding='utf-8'))
output += 'export type UserPreferences = ' + ts(prefs) + ';\n'
(root / 'web/lib/contracts.ts').write_text(output, encoding='utf-8')
subprocess.run(['node', str(root / 'web/node_modules/prettier/bin/prettier.cjs'), '--write',
                str(root / 'web/lib/contracts.ts')], check=True)
print('Generated BUILD-01 contract DTOs.')
