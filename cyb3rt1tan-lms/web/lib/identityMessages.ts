export const identityMessages = { en, vi };
export type IdentityKey = keyof typeof en;
export function identityError(locale: 'en' | 'vi', error: unknown): string {
  const code = error instanceof Error ? error.message : 'genericError';
  return identityMessages[locale][code as IdentityKey] || identityMessages[locale].genericError;
}
